import ExcelJS from 'exceljs';

export interface ExcelExtractPayload {
  title: string;
  sheetName: string;
  projectName?: string;
  companyName?: string;
  startDate?: string;
  endDate?: string;
  extractedBy?: string;
  rows: any[];
}

export class ReportsExcelBuilder {
  /**
   * Generates a professionally styled Excel workbook buffer
   */
  static async generateExtractWorkbook(payload: ExcelExtractPayload): Promise<Buffer> {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'Rebar Optima Reporting System';
    workbook.created = new Date();

    const sheet = workbook.addWorksheet(payload.sheetName.substring(0, 31), {
      views: [{ state: 'frozen', ySplit: 5 }], // Freeze top 5 rows (Title + Metadata + Headers)
    });

    const primaryColor = '1E3A8A'; // Deep Navy Blue
    const lightHeaderBg = 'F1F5F9'; // Slate 100

    // ─── 1. Title Block ───────────────────────────────────────────────────────
    sheet.mergeCells('A1:H1');
    const titleCell = sheet.getCell('A1');
    titleCell.value = `REBAR OPTIMA — ${payload.title.toUpperCase()}`;
    titleCell.font = { name: 'Calibri', size: 14, bold: true, color: { argb: 'FFFFFF' } };
    titleCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: primaryColor } };
    titleCell.alignment = { vertical: 'middle', indent: 1 };
    sheet.getRow(1).height = 28;

    // ─── 2. Metadata Subheader Rows ───────────────────────────────────────────
    sheet.getCell('A2').value = 'Project:';
    sheet.getCell('A2').font = { bold: true, size: 9 };
    sheet.getCell('B2').value = payload.projectName || 'All Projects';
    sheet.getCell('B2').font = { size: 9 };

    sheet.getCell('D2').value = 'Period:';
    sheet.getCell('D2').font = { bold: true, size: 9 };
    sheet.getCell('E2').value = payload.startDate && payload.endDate ? `${payload.startDate} to ${payload.endDate}` : 'All Time';
    sheet.getCell('E2').font = { size: 9 };

    sheet.getCell('A3').value = 'Generated By:';
    sheet.getCell('A3').font = { bold: true, size: 9 };
    sheet.getCell('B3').value = payload.extractedBy || 'Authorized User';
    sheet.getCell('B3').font = { size: 9 };

    sheet.getCell('D3').value = 'Export Date:';
    sheet.getCell('D3').font = { bold: true, size: 9 };
    sheet.getCell('E3').value = new Date().toISOString().replace('T', ' ').substring(0, 19);
    sheet.getCell('E3').font = { size: 9 };

    sheet.getRow(4).height = 8; // spacing row

    // ─── 3. Data Table Headers & Rows ─────────────────────────────────────────
    if (!payload.rows || payload.rows.length === 0) {
      sheet.getCell('A6').value = 'No records found for the selected criteria.';
      sheet.getCell('A6').font = { italic: true, color: { argb: '64748B' } };
      const buf = await workbook.xlsx.writeBuffer();
      return Buffer.from(buf);
    }

    // Determine column keys and format headers
    const rawKeys = Object.keys(payload.rows[0]);
    const headers = rawKeys.map(k => formatColumnHeader(k));

    const headerRow = sheet.getRow(5);
    headerRow.values = headers;
    headerRow.height = 24;

    headerRow.eachCell((cell) => {
      cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FFFFFF' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: primaryColor } };
      cell.alignment = { vertical: 'middle', horizontal: 'center' };
      cell.border = {
        top: { style: 'thin', color: { argb: 'CBD5E1' } },
        bottom: { style: 'medium', color: { argb: '0F172A' } },
        left: { style: 'thin', color: { argb: 'CBD5E1' } },
        right: { style: 'thin', color: { argb: 'CBD5E1' } },
      };
    });

    // Populate rows
    payload.rows.forEach((item, rIdx) => {
      const rowValues = rawKeys.map(k => item[k]);
      const row = sheet.addRow(rowValues);
      row.height = 20;

      const isEven = rIdx % 2 === 0;
      row.eachCell((cell, colNumber) => {
        cell.font = { name: 'Calibri', size: 9.5 };
        cell.alignment = { vertical: 'middle' };
        if (!isEven) {
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'F8FAFC' } };
        }

        // Check if value is number
        if (typeof cell.value === 'number') {
          cell.alignment = { vertical: 'middle', horizontal: 'right' };
        }

        cell.border = {
          top: { style: 'thin', color: { argb: 'E2E8F0' } },
          bottom: { style: 'thin', color: { argb: 'E2E8F0' } },
          left: { style: 'thin', color: { argb: 'E2E8F0' } },
          right: { style: 'thin', color: { argb: 'E2E8F0' } },
        };
      });
    });

    // Auto-fit column widths
    rawKeys.forEach((key, colIdx) => {
      let maxLen = headers[colIdx].length;
      for (let i = 0; i < Math.min(payload.rows.length, 100); i++) {
        const val = payload.rows[i][key];
        const len = val !== null && val !== undefined ? String(val).length : 0;
        if (len > maxLen) maxLen = len;
      }
      sheet.getColumn(colIdx + 1).width = Math.max(maxLen + 4, 12);
    });

    const buf = await workbook.xlsx.writeBuffer();
    return Buffer.from(buf);
  }
}

function formatColumnHeader(key: string): string {
  // Convert camelCase or snake_case to Title Case
  const words = key
    .replace(/([A-Z])/g, ' $1')
    .replace(/_/g, ' ')
    .trim()
    .split(' ');
  return words
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}
