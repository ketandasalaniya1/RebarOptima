import PDFDocument from 'pdfkit';
import { AggregatedReportData } from './reports.types';

export class ReportsPdfBuilder {
  /**
   * Generates a complete PDF document buffer for the aggregated report data
   */
  static async generate(data: AggregatedReportData): Promise<Buffer> {
    return new Promise<Buffer>((resolve, reject) => {
      const doc = new PDFDocument({
        size: 'A4',
        layout: 'portrait',
        margin: 36, // 0.5 inch margins
        info: {
          Title: `Rebar Optima Progress Report - ${data.metadata.projectName}`,
          Author: 'Rebar Optima SaaS Reporting System',
          Subject: `${data.metadata.reportMode.toUpperCase()} Report (${data.metadata.startDate} to ${data.metadata.endDate})`,
        },
        bufferPages: true,
      });

      const chunks: Buffer[] = [];
      doc.on('data', chunk => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', err => reject(err));

      const primaryColor = '#1e3a8a';   // Deep Blue
      const secondaryColor = '#0f172a'; // Slate 900
      const accentColor = '#2563eb';    // Bright Blue
      const borderColor = '#cbd5e1';    // Slate 300
      const lightBg = '#f8fafc';        // Slate 50
      const textMuted = '#64748b';      // Slate 500

      const pageWidth = doc.page.width;
      const margin = 36;
      const contentWidth = pageWidth - margin * 2;

      // ─── Header Section ──────────────────────────────────────────────────
      const renderHeader = () => {
        doc.rect(margin, margin, contentWidth, 68).fill(secondaryColor);

        doc.fillColor('#ffffff').fontSize(16).font('Helvetica-Bold')
          .text('REBAR OPTIMA', margin + 16, margin + 14);
        
        doc.fillColor('#93c5fd').fontSize(8).font('Helvetica')
          .text('CONSTRUCTION MANAGEMENT & REBAR INTELLIGENCE', margin + 16, margin + 34);

        const modeBadge = data.metadata.reportMode === 'detailed' ? 'DETAILED OPERATIONAL REPORT' : 'EXECUTIVE SUMMARY REPORT';
        doc.fillColor('#38bdf8').fontSize(11).font('Helvetica-Bold')
          .text(modeBadge, margin, margin + 16, { align: 'right', width: contentWidth - 16 });

        const dateRange = `${data.metadata.startDate} to ${data.metadata.endDate}`;
        doc.fillColor('#cbd5e1').fontSize(8).font('Helvetica')
          .text(`Reporting Period: ${dateRange}`, margin, margin + 34, { align: 'right', width: contentWidth - 16 });

        // Metadata Subheader Box
        const metaY = margin + 74;
        doc.rect(margin, metaY, contentWidth, 36).fill(lightBg).stroke(borderColor);

        doc.fillColor(secondaryColor).fontSize(8).font('Helvetica-Bold')
          .text('Project:', margin + 12, metaY + 8)
          .font('Helvetica').text(data.metadata.projectName || 'All Projects', margin + 50, metaY + 8);

        if (data.metadata.projectCode) {
          doc.font('Helvetica-Bold').text('Code:', margin + 200, metaY + 8)
            .font('Helvetica').text(data.metadata.projectCode, margin + 230, metaY + 8);
        }

        doc.font('Helvetica-Bold').text('Generated By:', margin + 12, metaY + 20)
          .font('Helvetica').text(data.metadata.generatedBy.name, margin + 74, metaY + 20);

        doc.font('Helvetica-Bold').text('Generated At:', margin + contentWidth - 180, metaY + 20)
          .font('Helvetica').text(data.metadata.generatedAt.replace('T', ' ').substring(0, 19), margin + contentWidth - 116, metaY + 20);

        doc.y = metaY + 48;
      };

      renderHeader();

      // Helper: Section Title
      const renderSectionHeading = (title: string, badge?: string) => {
        if (doc.y > doc.page.height - 100) {
          doc.addPage();
          renderHeader();
        }
        const curY = doc.y;
        doc.rect(margin, curY, contentWidth, 22).fill(primaryColor);
        doc.fillColor('#ffffff').fontSize(10).font('Helvetica-Bold')
          .text(title.toUpperCase(), margin + 10, curY + 6);

        if (badge) {
          doc.fillColor('#bfdbfe').fontSize(8).font('Helvetica-Bold')
            .text(badge, margin, curY + 6, { align: 'right', width: contentWidth - 10 });
        }
        doc.y = curY + 28;
      };

      // Helper: KPI Cards Grid
      const renderKpiCards = (cards: Array<{ label: string; value: string | number; color?: string }>) => {
        if (doc.y > doc.page.height - 80) {
          doc.addPage();
          renderHeader();
        }
        const cardGap = 8;
        const count = cards.length;
        const cardWidth = (contentWidth - cardGap * (count - 1)) / count;
        const curY = doc.y;

        cards.forEach((card, idx) => {
          const cardX = margin + idx * (cardWidth + cardGap);
          doc.rect(cardX, curY, cardWidth, 42).fill(lightBg).stroke(borderColor);
          doc.fillColor(textMuted).fontSize(7).font('Helvetica-Bold')
            .text(card.label.toUpperCase(), cardX + 6, curY + 6, { width: cardWidth - 12, align: 'center' });
          doc.fillColor(card.color || secondaryColor).fontSize(13).font('Helvetica-Bold')
            .text(String(card.value), cardX + 6, curY + 20, { width: cardWidth - 12, align: 'center' });
        });

        doc.y = curY + 50;
      };

      // ─── 1. Task & Progress Section ────────────────────────────────────────
      if (data.sections.tasksAndProgress) {
        const sec = data.sections.tasksAndProgress;
        renderSectionHeading('1. Task & Progress', `${sec.summary.overallProgressPercent}% Completed`);

        renderKpiCards([
          { label: 'Total Tasks', value: sec.summary.totalTasks },
          { label: 'Completed', value: sec.summary.completedTasks, color: '#16a34a' },
          { label: 'In Progress', value: sec.summary.inProgressTasks, color: '#2563eb' },
          { label: 'Not Started', value: sec.summary.notStartedTasks, color: '#64748b' },
          { label: 'Blocked / Risk', value: sec.summary.blockedTasks, color: '#dc2626' },
          { label: 'Workers Active', value: sec.summary.totalAllocatedWorkers, color: '#d97706' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          // Table header
          const cols = [
            { header: 'WBS', width: 45 },
            { header: 'Task Name', width: 140 },
            { header: 'Status', width: 75 },
            { header: 'Progress', width: 55 },
            { header: 'Planned Finish', width: 70 },
            { header: 'Assigned / Workers', width: 85 },
            { header: 'Qty / Unit', width: 53 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.wbsCode || '-',
            it.name,
            it.status,
            `${it.progressPercentage}%`,
            it.plannedFinish || '-',
            `${it.assignedUserName || 'Unassigned'} (${it.workerCount || 0}w)`,
            it.completedQty !== undefined && it.plannedQty !== undefined ? `${it.completedQty}/${it.plannedQty} ${it.unit}` : (it.unit || '-'),
          ]), () => renderHeader());
        }
      }

      // ─── 2. Issues & Incidents Section ────────────────────────────────────
      if (data.sections.issues) {
        const sec = data.sections.issues;
        renderSectionHeading('2. Site Incidents & Issues', `${sec.summary.totalIncidents} Total`);

        renderKpiCards([
          { label: 'Total Incidents', value: sec.summary.totalIncidents },
          { label: 'Reported', value: sec.summary.reported, color: '#d97706' },
          { label: 'Investigating', value: sec.summary.investigating, color: '#2563eb' },
          { label: 'Resolved', value: sec.summary.resolved, color: '#16a34a' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'Inc #', width: 65 },
            { header: 'Date', width: 60 },
            { header: 'Type', width: 75 },
            { header: 'Description', width: 180 },
            { header: 'Status', width: 75 },
            { header: 'Reported By', width: 68 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.incidentNumber,
            it.date,
            it.incidentType,
            it.description,
            it.status,
            it.reportedBy,
          ]), () => renderHeader());
        }
      }

      // ─── 3. Inventory Stock Balances ───────────────────────────────────────
      if (data.sections.inventory) {
        const sec = data.sections.inventory;
        renderSectionHeading('3. Inventory & Stock Balances');

        renderKpiCards([
          { label: 'Active Materials', value: sec.summary.totalMaterials },
          { label: 'Adequate Stock', value: sec.summary.normalCount, color: '#16a34a' },
          { label: 'Low Stock Alert', value: sec.summary.lowStockCount, color: '#d97706' },
          { label: 'Out of Stock', value: sec.summary.outOfStockCount, color: '#dc2626' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'Code', width: 55 },
            { header: 'Material Name', width: 155 },
            { header: 'Category', width: 90 },
            { header: 'Current Stock', width: 85 },
            { header: 'Low Threshold', width: 70 },
            { header: 'Status', width: 68 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.materialCode || '-',
            it.name,
            it.category,
            `${it.currentBalance} ${it.uom}`,
            `${it.lowStockThreshold} ${it.uom}`,
            it.status,
          ]), () => renderHeader());
        }
      }

      // ─── 4. GRN / Material Inward ──────────────────────────────────────────
      if (data.sections.grn) {
        const sec = data.sections.grn;
        renderSectionHeading('4. Goods Receipt Notes (GRN - Inward)');

        renderKpiCards([
          { label: 'Inward Challans', value: sec.summary.totalInwardEntries },
          { label: 'Received Items', value: sec.summary.totalReceivedItems },
          { label: 'Accepted Qty', value: sec.summary.totalAcceptedQuantity, color: '#16a34a' },
          { label: 'Damaged Qty', value: sec.summary.totalDamagedQuantity, color: '#dc2626' },
          { label: 'Active Vendors', value: sec.summary.totalVendorsCount, color: '#2563eb' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'GRN #', width: 80 },
            { header: 'Receipt Date', width: 65 },
            { header: 'Vendor Name', width: 125 },
            { header: 'Challan #', width: 80 },
            { header: 'Items (Accepted)', width: 110 },
            { header: 'Received By', width: 63 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.inwardNumber,
            it.receiptDate,
            it.vendorName,
            it.vendorChallanNumber || '-',
            it.items.map((i: any) => `${i.materialName}: ${i.acceptedQuantity} ${i.uom}`).join(', '),
            it.receivedBy,
          ]), () => renderHeader());
        }
      }

      // ─── 5. Material Issued ────────────────────────────────────────────────
      if (data.sections.materialIssued) {
        const sec = data.sections.materialIssued;
        renderSectionHeading('5. Material Issued (Outward)');

        renderKpiCards([
          { label: 'Issue Entries', value: sec.summary.totalOutwardEntries },
          { label: 'Total Qty Issued', value: sec.summary.totalQuantityIssued },
          { label: 'Returnable Tools', value: sec.summary.returnableCount, color: '#2563eb' },
          { label: 'Consumable/Non-Ret', value: sec.summary.nonReturnableCount, color: '#64748b' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'Issue #', width: 75 },
            { header: 'Date', width: 60 },
            { header: 'Material', width: 115 },
            { header: 'Issued Qty', width: 65 },
            { header: 'Recipient & Agency', width: 115 },
            { header: 'Location & Purpose', width: 93 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.outwardNumber,
            it.issueDateTime,
            it.materialName,
            `${it.quantity} ${it.uom}`,
            `${it.personReceiving} (${it.agency || 'Site'})`,
            `${it.location || '-'}: ${it.purpose || '-'}`,
          ]), () => renderHeader());
        }
      }

      // ─── 6. Site Transfer ──────────────────────────────────────────────────
      if (data.sections.siteTransfer) {
        const sec = data.sections.siteTransfer;
        renderSectionHeading('6. Store & Site Transfers');

        renderKpiCards([
          { label: 'Transfers Executed', value: sec.summary.totalTransfers },
          { label: 'Total Qty Transferred', value: sec.summary.totalQuantityTransferred, color: '#2563eb' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'TRF #', width: 75 },
            { header: 'Date', width: 60 },
            { header: 'Source Store', width: 95 },
            { header: 'Destination Store', width: 95 },
            { header: 'Material & Qty', width: 120 },
            { header: 'Authorized By', width: 78 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.transferNumber,
            it.transferDate,
            it.sourceStoreName,
            it.destinationStoreName,
            `${it.materialName} (${it.quantity} ${it.uom})`,
            it.responsibleUser,
          ]), () => renderHeader());
        }
      }

      // ─── 7. Attendance Section ─────────────────────────────────────────────
      if (data.sections.attendance) {
        const sec = data.sections.attendance;
        renderSectionHeading('7. Manpower & Attendance', `${sec.summary.totalWorkedPersonDays} Worked Person-Days`);

        renderKpiCards([
          { label: 'Total Person-Days', value: sec.summary.totalWorkedPersonDays, color: '#16a34a' },
          { label: 'Company Labour', value: sec.summary.companyLabourWorkedDays },
          { label: 'Contractor Labour', value: sec.summary.contractorLabourWorkedDays },
          { label: 'Contractor Workforce', value: sec.summary.workforcePersonDays, color: '#2563eb' },
          { label: 'Present Headcount', value: sec.summary.presentHeadcountTotal },
          { label: 'Half-Day Count', value: sec.summary.halfDayHeadcountTotal, color: '#d97706' },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'Worker / Gang Name', width: 140 },
            { header: 'Category', width: 95 },
            { header: 'Contractor', width: 95 },
            { header: 'Date', width: 60 },
            { header: 'Status / Attendance', width: 70 },
            { header: 'Worked Days', width: 63 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.slice(0, 150).map(it => [
            it.workerName,
            it.category,
            it.contractorName,
            it.date,
            it.status,
            `${it.workedDays}d`,
          ]), () => renderHeader());
        }
      }

      // ─── 8. Payables & Expenses Section ────────────────────────────────────
      if (data.sections.payables) {
        const sec = data.sections.payables;
        renderSectionHeading('8. Payables & Site Expenses (Petty Cash)');

        renderKpiCards([
          { label: 'Total Debits (Spent)', value: `INR ${sec.summary.totalDebits.toLocaleString()}`, color: '#dc2626' },
          { label: 'Total Credits (Funds)', value: `INR ${sec.summary.totalCredits.toLocaleString()}`, color: '#16a34a' },
          { label: 'Net Expenditure', value: `INR ${sec.summary.netExpenses.toLocaleString()}`, color: '#2563eb' },
          { label: 'Transactions', value: sec.summary.transactionCount },
        ]);

        if (data.metadata.reportMode === 'detailed' && sec.items && sec.items.length > 0) {
          const cols = [
            { header: 'Date', width: 65 },
            { header: 'Type', width: 50 },
            { header: 'Category', width: 85 },
            { header: 'Paid To / Person', width: 105 },
            { header: 'Amount (INR)', width: 75 },
            { header: 'Mode & Bill #', width: 75 },
            { header: 'Remarks', width: 68 },
          ];

          renderTable(doc, margin, contentWidth, cols, sec.items.map(it => [
            it.date,
            it.type,
            it.category,
            it.paidTo,
            Number(it.amount).toLocaleString(),
            `${it.paymentMode} ${it.billNumber ? `(#${it.billNumber})` : ''}`,
            it.remarks,
          ]), () => renderHeader());
        }
      }

      // ─── 9. Optional Photos Gallery ────────────────────────────────────────
      if (data.photos && data.photos.length > 0) {
        doc.addPage();
        renderHeader();
        renderSectionHeading('Report Attachments & Photographic Evidence', `${data.photos.length} Photos`);

        let photoX = margin;
        let photoY = doc.y;
        const photoWidth = (contentWidth - 16) / 2;
        const photoHeight = 110;

        data.photos.forEach((ph, pIdx) => {
          if (photoY + photoHeight + 35 > doc.page.height - 30) {
            doc.addPage();
            renderHeader();
            renderSectionHeading('Report Attachments (Continued)');
            photoX = margin;
            photoY = doc.y;
          }

          // Photo border & background card
          doc.rect(photoX, photoY, photoWidth, photoHeight).fill('#000000').stroke(borderColor);
          doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold')
            .text(`[ Image: ${ph.source} ]`, photoX + 10, photoY + 45, { width: photoWidth - 20, align: 'center' });

          // Caption
          doc.fillColor(secondaryColor).fontSize(7).font('Helvetica-Bold')
            .text(ph.title, photoX, photoY + photoHeight + 4, { width: photoWidth });
          if (ph.date) {
            doc.fillColor(textMuted).fontSize(6).font('Helvetica')
              .text(`Date: ${ph.date}`, photoX, photoY + photoHeight + 14, { width: photoWidth });
          }

          if (pIdx % 2 === 0) {
            photoX = margin + photoWidth + 16;
          } else {
            photoX = margin;
            photoY += photoHeight + 32;
          }
        });
      }

      // ─── Multi-Page Footers (Page X of Y) ──────────────────────────────────
      const range = doc.bufferedPageRange();
      for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);

        // Ensure bottom margin is 0 during footer stamp to prevent phantom extra pages
        const origBottom = doc.page.margins.bottom;
        doc.page.margins.bottom = 0;

        const footerY = doc.page.height - 24;
        doc.rect(margin, footerY - 4, contentWidth, 0.5).fill(borderColor);

        doc.fillColor(textMuted).fontSize(7).font('Helvetica')
          .text('Rebar Optima Construction SaaS • Centralized Operational Report', margin, footerY, { align: 'left' });

        doc.fillColor(textMuted).fontSize(7).font('Helvetica')
          .text(`Page ${i + 1} of ${range.count}`, margin, footerY, { align: 'right', width: contentWidth });

        doc.page.margins.bottom = origBottom;
      }

      doc.end();
    });
  }
}

/**
 * Universal table renderer with pagination support
 */
function renderTable(
  doc: PDFKit.PDFDocument,
  startX: number,
  tableWidth: number,
  cols: Array<{ header: string; width: number }>,
  rows: string[][],
  onNewPage: () => void
) {
  const rowHeight = 16;
  const headerHeight = 18;
  const secondaryColor = '#0f172a';
  const borderColor = '#e2e8f0';

  const renderTableHeader = () => {
    let curX = startX;
    const curY = doc.y;
    doc.rect(startX, curY, tableWidth, headerHeight).fill('#e2e8f0');

    cols.forEach(col => {
      doc.fillColor(secondaryColor).fontSize(7).font('Helvetica-Bold')
        .text(col.header, curX + 4, curY + 5, { width: col.width - 8, lineBreak: false });
      curX += col.width;
    });

    doc.y = curY + headerHeight;
  };

  renderTableHeader();

  rows.forEach((row, rIdx) => {
    if (doc.y + rowHeight > doc.page.height - 35) {
      doc.addPage();
      onNewPage();
      renderTableHeader();
    }

    const curY = doc.y;
    const isEven = rIdx % 2 === 0;
    doc.rect(startX, curY, tableWidth, rowHeight).fill(isEven ? '#ffffff' : '#f8fafc').stroke(borderColor);

    let curX = startX;
    cols.forEach((col, cIdx) => {
      const textVal = String(row[cIdx] || '');
      doc.fillColor('#334155').fontSize(6.5).font('Helvetica')
        .text(textVal, curX + 4, curY + 4, { width: col.width - 8, height: rowHeight - 6, lineBreak: false, ellipsis: true });
      curX += col.width;
    });

    doc.y = curY + rowHeight;
  });

  doc.y += 12; // spacing after table
}
